export function dt(key: string, vars?: Record<string, string | number>): string {
  let s = (i18n.lang === 'ru' ? ru : en)[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** A key the UI may not know (a check code, a quote group the server added): its text, else the fallback as given. */
export function known(key: string, fallback: string, vars?: Record<string, string | number>): string {
  return key in en ? dt(key, vars) : fallback;
}

/** A layout's pattern by name ('dice' → 'Dice pips'), or the name itself for one the UI does not know. */
export function patternName(p: string): string {
  return known(`pattern_${p}`, p);
}

/** A quote line's note in the UI language, from its numbers (the server's English note when it has none). */
export function groupNote(g: { key: string; note: string; data?: Record<string, number | string> }): string {
  return g.data && `n_${g.key}` in en ? dt(`n_${g.key}`, g.data) : g.note;
}

export function usd(v: number | null | undefined, digits = 2): string {
  if (v == null) return '—';
  return `$${v.toLocaleString(i18n.lang === 'ru' ? 'ru-RU' : 'en-US', { minimumFractionDigits: v < 1 && digits > 2 ? digits : Math.min(2, digits), maximumFractionDigits: digits })}`;
}

export function kzt(v: number): string {
  return `${new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 0 }).format(v).replace(/\s/g, ' ')} ₸`;
}

export function date(iso: string): string {
  return new Date(iso + 'T12:00:00').toLocaleDateString(i18n.lang === 'ru' ? 'ru-RU' : 'en-GB', { day: 'numeric', month: 'short' });
}
