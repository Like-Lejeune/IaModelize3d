function initial(): 'en' | 'ru' {
  try {
    const v = localStorage.getItem('fw_lang');
    if (v === 'ru' || v === 'en') return v;
  } catch {
    /* storage unavailable */
  }
  if (typeof navigator !== 'undefined') {
    const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
    if (langs.some((l) => /^(ru|kk|be|uk)\b/i.test(l ?? ''))) return 'ru';
  }
  return 'en';
}

export const i18n = $state({ lang: initial() as 'en' | 'ru' });

export function toggleLang() {
  i18n.lang = i18n.lang === 'en' ? 'ru' : 'en';
  try {
    localStorage.setItem('fw_lang', i18n.lang);
  } catch {
    /* ignore */
  }
  // <html lang> follows in routes/+layout.svelte
}

/** t('usage_of', { a: '$1', b: '$2' }) fills {placeholders}. */
const RU_UNITS: Record<string, string> = { mm: 'мм', cm: 'см', m: 'м', g: 'г', s: 'с', min: 'мин', mm2: 'мм²', mm3: 'мм³' };
/** Units in the UI language; degrees read better as a symbol in both. */
export function unitLabel(u: string): string {
  if (u === 'deg' || u === 'degrees') return '°';
  return i18n.lang === 'ru' ? (RU_UNITS[u] ?? u) : u;
}

/** The server names fresh projects in English; show that default in the UI language. */
export function projectTitle(title?: string | null): string {
  return !title || title === 'New project' ? t('new_project') : title;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = (i18n.lang === 'ru' ? ru[key] : undefined) ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** s is key's text in either language (an error kept from before a language switch reads the same). */
export function isText(s: string | null | undefined, key: string): boolean {
  return s != null && (s === en[key] || s === ru[key]);
}

/** Count with a correctly declined noun: plural(3, ['note', 'notes'], ['заметка', 'заметки', 'заметок']). */
export function plural(n: number, en: [string, string], ru: [string, string, string]): string {
  if (i18n.lang !== 'ru') return `${n} ${n === 1 ? en[0] : en[1]}`;
  const m10 = n % 10, m100 = n % 100;
  const w = m10 === 1 && m100 !== 11 ? ru[0] : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? ru[1] : ru[2];
  return `${n} ${w}`;
}

export function ago(ts: number): string {
  const s = Date.now() / 1000 - ts;
  if (s < 3600) return t('ago_min', { n: Math.max(1, Math.round(s / 60)) });
  if (s < 86400) return t('ago_h', { n: Math.round(s / 3600) });
  return t('ago_d', { n: Math.round(s / 86400) });
}

export function fmtDuration(sec: number): string {
  if (!isFinite(sec) || sec < 0) return '';
  const S = i18n.lang === 'ru' ? 'с' : 's';
  if (sec < 60) return `${Math.round(sec)} ${S}`;
  const m = Math.floor(sec / 60);
  const s = Math.round(sec % 60);
  return s ? `${m} ${t('minutes')} ${s} ${S}` : `${m} ${t('minutes')}`;
}

export function fmtMinutes(min: number): string {
  if (!isFinite(min)) return '—';
  if (min < 60) return `${Math.max(1, Math.round(min))} ${t('minutes')}`;
  const h = Math.floor(min / 60);
  return `${h} ${i18n.lang === 'ru' ? 'ч' : 'h'} ${Math.round(min % 60)} ${t('minutes')}`;
}

/** A board part as people name it: 'usb' -> 'USB', 'btn_reset' -> 'RESET', 'pcb' -> 'Board'. */
export function partName(id: string): string {
  const key = `part.${id.toLowerCase()}`;
  if (en[key]) return t(key);
  const s = id.replace(/(^|_)(btn|button)_/gi, '$1').replace(/_/g, ' ');
  return s.length <= 8 ? s.toUpperCase() : s;
}

/** A measured value in the UI language's units: mm to 0.01, mm³ whole, % to 0.1. */
export function fmtValue(v: number | null | undefined, unit?: string): string {
  if (v == null || !isFinite(v)) return '';
  const n = unit === 'mm3' ? (v >= 10 ? Math.round(v) : +v.toFixed(2)) : unit === '%' ? +v.toFixed(1) : +v.toFixed(2);
  return unit === '%' ? `${n} %` : unit ? `${n} ${unitLabel(unit)}` : String(n);
}

/** The clearance of a port: the check's bisection stops at 2 mm, so 1.998 reads "2 mm or more". */
export function fmtClearance(mm: number): string {
  return mm >= 1.99 ? t('enc_at_least', { v: `2 ${unitLabel('mm')}` }) : fmtValue(mm, 'mm');
}

/** One finding of the case check in the UI language (the kernel's own text, f.msg, is English). */
export function encText(f: EnclosureFinding): string {
  const p = partName(f.part);
  const v = f.code.startsWith('port_') && f.value != null ? fmtClearance(f.value) : fmtValue(f.value, f.unit);
  if (f.code === 'pcb_seated') return f.severity === 'info' ? t('f.pcb_seated', { n: f.value ?? 0 }) : t(`f.pcb_seated.${f.severity}`);
  if (f.code === 'light_window' && !f.value) return t('f.light_window.open', { p });
  const own = `f.${f.code}.${f.severity}`;
  const key = f.severity !== 'info' && en[own] ? own : `f.${f.code}`;
  return en[key] ? t(key, { p, v }) : f.msg;
}
