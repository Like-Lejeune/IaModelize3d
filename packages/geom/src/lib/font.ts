// Returns polylines in mm: glyph height = `size`, origin at the baseline start.
export function layoutText(text: string, size: number, spacing = 1.5): { lines: Stroke[]; width: number } {
  const k = size / 6;
  const lines: Stroke[] = [];
  let x = 0;
  for (const ch of text.toUpperCase()) {
    if (ch === ' ') {
      x += 4 * k;
      continue;
    }
    const glyph = GLYPHS[ch] ?? GLYPHS['#'];
    for (const stroke of glyph) lines.push(stroke.map(([gx, gy]) => [x + gx * k, gy * k]));
    x += (4 + spacing) * k;
  }
  return { lines, width: Math.max(0, x - spacing * k) };
}
